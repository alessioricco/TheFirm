def seed_store(
    root: Path,
    *,
    venue: str = "kraken",
    instrument: str = "BTC-USD",
    provider_symbol: str = "XBTUSD",
    tf: str = "1d",
    n: int = 2_000,
    seed: int = 7,
    start: datetime = datetime(2019, 1, 1, tzinfo=UTC),
    chunk: int = 720,
    delisted_at: datetime | None = None,
    **walk: float,
) -> None:
    """Write an instrument record and overlapping synthetic captures (Kraken-style
    720-bar pages, each including the still-forming bar the API returns)."""
    step = tf_seconds(tf)
    bars = synthetic_bars(n + 1, seed=seed, start=start, tf=tf, **walk)  # +1 = forming bar
    write_instrument(
        root,
        InstrumentRecord(
            venue=venue,
            instrument=instrument,
            asset_class="crypto",
            base=instrument.split("-")[0],
            quote=instrument.split("-")[1],
            provider_symbols={venue: provider_symbol},
            listed_at=start,
            delisted_at=delisted_at,
            known_at=start,
        ),
    )
    pages = range(0, n, chunk - 20)  # 20-bar overlap between pages
    for first in pages:
        last = min(first + chunk, n + 1)
        page = bars[first:last]
        forming_open = page[-1].open_time
        captured_at = datetime.fromtimestamp(forming_open + step // 2, tz=UTC)
        if venue == "kraken":
            payload = kraken_ohlc_payload(page)
        elif venue == "coinbase":
            payload = coinbase_candles_payload(page)
        elif venue == "binance":
            payload = binance_klines_payload(page, tf)
        else:
            raise ValueError(f"no synthetic bar format for {venue!r}")
        write_capture(
            root,
            payload,
            provider=venue,
            kind="bars",
            provider_symbol=provider_symbol,
            tf=tf,
            fmt="json",
            captured_at=captured_at,
            request={"synthetic_seed": seed, "first": first},
            via="firm.data.synthetic",
            licence=SYNTHETIC_LICENCE,
            capture_method="synthetic",
        )
        if last >= n + 1:
            break


def last_closed(start: datetime, n: int, tf: str = "1d") -> datetime:
    """Close time of the n-th bar from `start`."""
    return start + timedelta(seconds=n * tf_seconds(tf))


