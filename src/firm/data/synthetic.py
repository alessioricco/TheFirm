"""Deterministic synthetic market data in the providers' own formats.

Tests use only this: the repo is public and real provider data never goes in
it. Prices are invented (regime-switching random walk with persistent
drifts), but the bytes follow the Kraken / Coinbase formats exactly, so the
real parsers, normalizer and dataset code run end to end.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path

import numpy as np

from firm.core.timeframes import tf_seconds
from firm.data.reference import InstrumentRecord, write_instrument
from firm.data.store import write_capture

NS = 1_000_000_000
SYNTHETIC_LICENCE = "synthetic: generated by firm.data.synthetic, no provider data"


@dataclass(frozen=True)
class SyntheticBar:
    open_time: int  # unix seconds
    open: float
    high: float
    low: float
    close: float
    volume: float


def synthetic_bars(
    n: int,
    *,
    seed: int,
    start: datetime,
    tf: str = "1d",
    start_price: float = 20_000.0,
    drift: float = 0.005,
    vol: float = 0.015,
    regime_bars: tuple[int, int] = (60, 180),
) -> list[SyntheticBar]:
    """`n` bars from `start`; drift flips sign between regimes of random length."""
    rng = np.random.default_rng(seed)
    step = tf_seconds(tf)
    t0 = int(start.timestamp())
    mus = np.empty(n)
    i, sign = 0, 1.0
    while i < n:
        length = int(rng.integers(regime_bars[0], regime_bars[1] + 1))
        mus[i : i + length] = sign * drift
        sign = -sign
        i += length
    rets = mus + vol * rng.standard_normal(n)
    closes = start_price * np.exp(np.cumsum(rets))
    bars = []
    prev = start_price
    for k in range(n):
        o = round(prev, 2)
        c = round(float(closes[k]), 2)
        wick = abs(vol * rng.standard_normal()) * 0.5
        h = round(max(o, c) * (1 + wick), 2)
        lo = round(min(o, c) * (1 - wick), 2)
        v = round(float(rng.uniform(500, 1500)), 6)
        bars.append(SyntheticBar(t0 + k * step, o, h, lo, c, v))
        prev = c
    return bars


def kraken_ohlc_payload(bars: list[SyntheticBar], pair_key: str = "XXBTZUSD") -> bytes:
    rows = [
        [
            b.open_time,
            f"{b.open:.2f}",
            f"{b.high:.2f}",
            f"{b.low:.2f}",
            f"{b.close:.2f}",
            f"{(b.open + b.close) / 2:.2f}",
            f"{b.volume:.8f}",
            100,
        ]
        for b in bars
    ]
    last = bars[-1].open_time if bars else 0
    return json.dumps({"error": [], "result": {pair_key: rows, "last": last}}).encode()


def coinbase_candles_payload(bars: list[SyntheticBar]) -> bytes:
    rows = [[b.open_time, b.low, b.high, b.open, b.close, b.volume] for b in reversed(bars)]
    return json.dumps(rows).encode()


def seed_store(
    root: Path,
    *,
    venue: str = "kraken",
    instrument: str = "BTC-USD",
    provider_symbol: str = "XBTUSD",
    tf: str = "1d",
    n: int = 2_000,
    seed: int = 7,
    start: datetime = datetime(2019, 1, 1, tzinfo=UTC),
    chunk: int = 720,
    delisted_at: datetime | None = None,
    **walk: float,
) -> None:
    """Write an instrument record and overlapping synthetic captures (Kraken-style
    720-bar pages, each including the still-forming bar the API returns)."""
    step = tf_seconds(tf)
    bars = synthetic_bars(n + 1, seed=seed, start=start, tf=tf, **walk)  # +1 = forming bar
    write_instrument(
        root,
        InstrumentRecord(
            venue=venue,
            instrument=instrument,
            asset_class="crypto",
            base=instrument.split("-")[0],
            quote=instrument.split("-")[1],
            provider_symbols={venue: provider_symbol},
            listed_at=start,
            delisted_at=delisted_at,
            known_at=start,
        ),
    )
    pages = range(0, n, chunk - 20)  # 20-bar overlap between pages
    for first in pages:
        last = min(first + chunk, n + 1)
        page = bars[first:last]
        forming_open = page[-1].open_time
        captured_at = datetime.fromtimestamp(forming_open + step // 2, tz=UTC)
        payload = kraken_ohlc_payload(page) if venue == "kraken" else coinbase_candles_payload(page)
        write_capture(
            root,
            payload,
            provider=venue,
            kind="bars",
            provider_symbol=provider_symbol,
            tf=tf,
            fmt="json",
            captured_at=captured_at,
            request={"synthetic_seed": seed, "first": first},
            via="firm.data.synthetic",
            licence=SYNTHETIC_LICENCE,
            capture_method="synthetic",
        )
        if last >= n + 1:
            break


def last_closed(start: datetime, n: int, tf: str = "1d") -> datetime:
    """Close time of the n-th bar from `start`."""
    return start + timedelta(seconds=n * tf_seconds(tf))
