"""Deterministic synthetic market data in the providers' own formats.

Tests use only this: the repo is public and real provider data never goes in
it. Prices are invented (regime-switching random walk with persistent
drifts), but the bytes follow the Kraken / Coinbase formats exactly, so the
real parsers, normalizer and dataset code run end to end.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path

import numpy as np

from firm.core.timeframes import tf_seconds
from firm.data.reference import InstrumentRecord, write_instrument
from firm.data.store import write_capture

NS = 1_000_000_000
SYNTHETIC_LICENCE = "synthetic: generated by firm.data.synthetic, no provider data"


@dataclass(frozen=True)
class SyntheticBar:
    open_time: int  # unix seconds
    open: float
    high: float
    low: float
    close: float
    volume: float


def synthetic_bars(
    n: int,
    *,
    seed: int,
    start: datetime,
    tf: str = "1d",
    start_price: float = 20_000.0,
    drift: float = 0.005,
    vol: float = 0.015,
    regime_bars: tuple[int, int] = (60, 180),
) -> list[SyntheticBar]:
    """`n` bars from `start`; drift flips sign between regimes of random length."""
    rng = np.random.default_rng(seed)
    step = tf_seconds(tf)
    t0 = int(start.timestamp())
    mus = np.empty(n)
    i, sign = 0, 1.0
    while i < n:
        length = int(rng.integers(regime_bars[0], regime_bars[1] + 1))
        mus[i : i + length] = sign * drift
        sign = -sign
        i += length
    rets = mus + vol * rng.standard_normal(n)
    closes = start_price * np.exp(np.cumsum(rets))
    bars = []
    prev = start_price
    for k in range(n):
        o = round(prev, 2)
        c = round(float(closes[k]), 2)
        wick = abs(vol * rng.standard_normal()) * 0.5
        h = round(max(o, c) * (1 + wick), 2)
        lo = round(min(o, c) * (1 - wick), 2)
        v = round(float(rng.uniform(500, 1500)), 6)
        bars.append(SyntheticBar(t0 + k * step, o, h, lo, c, v))
        prev = c
    return bars


def kraken_ohlc_payload(bars: list[SyntheticBar], pair_key: str = "XXBTZUSD") -> bytes:
    rows = [
        [
            b.open_time,
            f"{b.open:.2f}",
            f"{b.high:.2f}",
            f"{b.low:.2f}",
            f"{b.close:.2f}",
            f"{(b.open + b.close) / 2:.2f}",
            f"{b.volume:.8f}",
            100,
        ]
        for b in bars
    ]
    last = bars[-1].open_time if bars else 0
    return json.dumps({"error": [], "result": {pair_key: rows, "last": last}}).encode()


def coinbase_candles_payload(bars: list[SyntheticBar]) -> bytes:
    rows = [[b.open_time, b.low, b.high, b.open, b.close, b.volume] for b in reversed(bars)]
    return json.dumps(rows).encode()


def binance_klines_payload(bars: list[SyntheticBar], tf: str = "1d") -> bytes:
    """Binance `/api/v3/klines`: oldest first; times in ms; prices as strings."""
    step_ms = tf_seconds(tf) * 1000
    rows = [
        [
            b.open_time * 1000,
            f"{b.open:.2f}",
            f"{b.high:.2f}",
            f"{b.low:.2f}",
            f"{b.close:.2f}",
            f"{b.volume:.8f}",
            b.open_time * 1000 + step_ms - 1,
            "0",
            100,
            "0",
            "0",
            "0",
        ]
        for b in bars
    ]
    return json.dumps(rows).encode()


def yahoo_chart_payload(bars: list[SyntheticBar], splits: list[tuple[int, int, int]] = ()) -> bytes:
    """Yahoo `/v8/finance/chart`: prices SPLIT-ADJUSTED as Yahoo serves them.

    `splits` are (unix time, numerator, denominator); bars before a split are
    divided by its ratio (volumes multiplied), exactly what Yahoo does.
    """

    def factor(t: int) -> float:
        f = 1.0
        for date, num, den in splits:
            if t < date:
                f *= num / den
        return f

    ts = [b.open_time for b in bars]
    quote = {
        k: [getattr(b, k) / factor(b.open_time) for b in bars]
        for k in ("open", "high", "low", "close")
    }
    quote["volume"] = [int(b.volume * factor(b.open_time)) for b in bars]
    doc = {
        "chart": {
            "result": [
                {
                    "meta": {"currency": "USD", "symbol": "SYNTH", "exchangeName": "NMS"},
                    "timestamp": ts,
                    "indicators": {"quote": [quote], "adjclose": [{"adjclose": quote["close"]}]},
                    "events": {
                        "splits": {
                            str(d): {
                                "date": d,
                                "numerator": n,
                                "denominator": m,
                                "splitRatio": f"{n}:{m}",
                            }
                            for d, n, m in splits
                        }
                    },
                }
            ],
            "error": None,
        }
    }
    return json.dumps(doc).encode()


